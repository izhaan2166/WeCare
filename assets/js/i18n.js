  var KEY = 'wecare-lang';
  var root = document.documentElement;
  var originals = new WeakMap();
  var attrOriginals = new WeakMap();
  var norm = function (s) { return s.replace(/\s+/g, ' ').trim(); };

  function textNodes() {
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        var p = n.parentNode;
        if (!p || /^(SCRIPT|STYLE|svg|use)$/.test(p.nodeName) || p.closest('svg,[data-i18n-skip],.logo')) return NodeFilter.FILTER_REJECT;
        return n.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    var out = []; while (walker.nextNode()) out.push(walker.currentNode); return out;
  }

  function apply(lang) {
    textNodes().forEach(function (n) {
      if (!originals.has(n)) originals.set(n, n.nodeValue);
      var orig = originals.get(n);
      var key = norm(orig);
      if (lang === 'en' || !DICT[key] || !DICT[key][lang]) { n.nodeValue = orig; return; }
      var lead = orig.match(/^\s*/)[0], trail = orig.match(/\s*$/)[0];
      n.nodeValue = lead + DICT[key][lang] + trail;
    });
    document.querySelectorAll('[placeholder],[aria-label]').forEach(function (el) {
      ['placeholder', 'aria-label'].forEach(function (a) {
        if (!el.hasAttribute(a)) return;
        var store = attrOriginals.get(el) || {}; if (!(a in store)) store[a] = el.getAttribute(a); attrOriginals.set(el, store);
        var k = norm(store[a]);
        el.setAttribute(a, lang !== 'en' && DICT[k] && DICT[k][lang] ? DICT[k][lang] : store[a]);
      });
    });
    root.lang = lang === 'en' ? 'en-IN' : lang;
    root.removeAttribute('data-lang-pending');
    document.querySelectorAll('[data-lang-select]').forEach(function (s) { s.value = lang; });
  }

  function set(lang) {
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    apply(lang);
  }

  window.WeCareI18n = { apply: apply, set: set, dict: DICT };
  var initial = 'en';
  try { initial = localStorage.getItem(KEY) || 'en'; } catch (e) {}
  document.addEventListener('DOMContentLoaded', function () {
    document.querySelectorAll('[data-lang-select]').forEach(function (s) {
      s.addEventListener('change', function () { set(s.value); });
    });
    if (initial !== 'en') apply(initial); else root.removeAttribute('data-lang-pending');
  });
